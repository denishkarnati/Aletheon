// Bundles site/tools/devices/*.json into site/assets/devices-data.js (window.DEVICES) for the Device Lab.
//   node site/tools/build-devices.mjs      (run from the project root; run verify-devices.mjs first so only verified models ship)
import * as fs from 'node:fs';
import * as path from 'node:path';

const dir = path.join('site', 'tools', 'devices');
const devices = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
const out = path.join('site', 'assets', 'devices-data.js');
fs.writeFileSync(
  out,
  `/* Generated by site/tools/build-devices.mjs from site/tools/devices/*.json. Facts cite the vendor datasheets by page; do not edit. */\nwindow.DEVICES=${JSON.stringify({ generated: new Date().toISOString().slice(0, 10), devices })};\n`,
);
console.log(`wrote ${out}: ${devices.length} devices (${devices.map((d) => d.part).join(', ')}), ${(fs.statSync(out).size / 1024).toFixed(0)} KB`);

// Driver-verified parts (register facts quoted from open-source drivers; run verify-driver-facts.mjs first). Kept in their own file so
// they cannot be mistaken for the datasheet-checked simulator models above.
const onlineDir = path.join('site', 'tools', 'devices-online');
const online = fs
  .readdirSync(onlineDir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(onlineDir, f), 'utf8')));
const onlineOut = path.join('site', 'assets', 'driver-facts-data.js');
fs.writeFileSync(
  onlineOut,
  `/* Generated by site/tools/build-devices.mjs from site/tools/devices-online/*.json. Facts quote open-source driver files at pinned commits; do not edit. */\nwindow.DRIVER_FACTS=${JSON.stringify({ generated: new Date().toISOString().slice(0, 10), parts: online })};\n`,
);
console.log(
  `wrote ${onlineOut}: ${online.length} driver-verified parts (${online.map((d) => d.part).join(', ')}), ${(fs.statSync(onlineOut).size / 1024).toFixed(0)} KB`,
);
