// Builds site/assets/rp2040-data.js: a compact slice of the REAL RP2040 register map (vendor CMSIS-SVD) for the website's
// live register explorer and claim auditor. Run from the project root:
//   npx esbuild site/tools/make-explorer-data.ts --bundle --platform=node --outfile=dist/make-explorer-data.cjs --log-level=warning
//   node dist/make-explorer-data.cjs
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { SvdStore } from '../../src/core/svd';

const SVD = 'https://raw.githubusercontent.com/raspberrypi/pico-sdk/master/src/rp2040/hardware_regs/RP2040.svd';
const PICK = ['UART0', 'UART1', 'SPI0', 'I2C0', 'TIMER', 'WATCHDOG', 'RESETS', 'PWM', 'ADC', 'RTC'];
const clip = (s: string | undefined, n: number) => (s ? (s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s) : '');

async function main(): Promise<void> {
  const store = new SvdStore(path.join(os.tmpdir(), 'aletheon-site-data'));
  const dev = await store.index(SVD);
  const out = {
    device: dev.name,
    source: SVD,
    sha256: dev.sha256,
    trust: dev.trust,
    peripherals: PICK.map((name) => {
      const f = store.findPeripherals(name, 'RP2040')[0];
      if (!f) throw new Error(`missing ${name}`);
      return {
        n: f.p.name,
        base: f.p.base,
        d: clip(f.p.description, 120),
        regs: f.p.registers.map((r) => ({
          n: r.name,
          o: r.offset,
          sz: r.size,
          rs: r.reset ?? null,
          a: r.access ?? null,
          d: clip(r.description, 110),
          f: r.fields.map((x) => [x.name, x.lsb, x.msb, clip(x.description, 96)]),
        })),
      };
    }),
  };
  const regs = out.peripherals.reduce((n, p) => n + p.regs.length, 0);
  const file = path.join(process.cwd(), 'site', 'assets', 'rp2040-data.js');
  fs.writeFileSync(
    file,
    `/* Generated by site/tools/make-explorer-data.ts from the vendor CMSIS-SVD. Do not edit. */\nwindow.RP2040=${JSON.stringify(out)};\n`,
  );
  console.log(
    `wrote ${file}: ${out.peripherals.length} peripherals, ${regs} registers, ${(fs.statSync(file).size / 1024).toFixed(0)} KB, sha256 ${dev.sha256?.slice(0, 12)}`,
  );
}
main();
