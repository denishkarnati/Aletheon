import { createHash } from 'node:crypto';

// How much weight a source deserves. The ledger records this next to every piece of evidence so a reader
// (or an auditor) can see that "[E5]" is a vendor PDF, a community mirror, or a measurement from the board.
export type TrustClass =
  | 'measured' // produced by running something on this machine/board: build, flash, serial capture
  | 'vendor-official' // served from the silicon vendor's own domain/repo
  | 'community-mirror' // third-party copy (GitHub mirrors, forums): useful, verify against the vendor
  | 'user-supplied' // local file the user provided: provenance is the user's responsibility
  | 'derived' // generated by a tool from other evidence (headers, REA output)
  | 'unknown';

// Hosts/repos treated as the vendor itself. Deliberately an allow-list: everything else is NOT vendor-official.
const VENDOR_HOSTS = [
  'espressif.com',
  'raspberrypi.com',
  'st.com',
  'microchip.com',
  'nordicsemi.com',
  'ti.com',
  'nxp.com',
  'infineon.com',
  'renesas.com',
  'silabs.com',
  'analog.com',
  'arduino.cc',
];
const VENDOR_GITHUB_ORGS = ['espressif', 'raspberrypi', 'nordicsemiconductor', 'stmicroelectronics', 'microchip-pic-avr-tools', 'nxp-mcuxpresso', 'infineon'];

// Places on a vendor's domain where anyone can post (forums, communities, Q&A, uploads). A vendor suffix does not make them the vendor.
const COMMUNITY_SUBDOMAIN =
  /^(community|communities|forum|forums|e2e|devzone|ez|discuss|answers|support-forum|social|blog|blogs|wiki|git|gist|files|uploads?|attachments?)[0-9]*\./;

export function classifyTrust(source: string): TrustClass {
  if (/^[a-zA-Z]:[\\/]/.test(source)) return 'user-supplied'; // C:\path would otherwise parse as a URL scheme
  let u: URL;
  try {
    u = new URL(source.split('#')[0].split('!')[0]);
  } catch {
    return /^[a-zA-Z]:[\\/]|^[./\\]|\//.test(source) ? 'user-supplied' : 'unknown';
  }
  if (u.protocol === 'file:') return 'user-supplied';
  const host = u.hostname.toLowerCase();
  if (host === 'raw.githubusercontent.com' || host === 'github.com') {
    const org = u.pathname.split('/')[1]?.toLowerCase() ?? '';
    // Issue and PR attachments live under a vendor's org path but are uploaded by anyone.
    if (/\/(files|assets|user-attachments)\//i.test(u.pathname)) return 'community-mirror';
    return VENDOR_GITHUB_ORGS.includes(org) ? 'vendor-official' : 'community-mirror';
  }
  if (host.endsWith('githubusercontent.com') || host === 'user-images.githubusercontent.com') return 'community-mirror';
  if (COMMUNITY_SUBDOMAIN.test(host)) return 'community-mirror';
  if (VENDOR_HOSTS.some((h) => host === h || host.endsWith('.' + h))) return 'vendor-official';
  return 'community-mirror';
}

// A source that was redirected is only as trustworthy as the weaker of where it was asked for and where it ended up.
export function weakestTrust(a: TrustClass, b: TrustClass): TrustClass {
  return TRUST_RANK[a] <= TRUST_RANK[b] ? a : b;
}

export const sha256 = (bytes: Uint8Array | string): string => createHash('sha256').update(bytes).digest('hex');

// Stable short id for an indexed source (URL or path); names its files in the store.
export const sourceId = (source: string): string => createHash('sha1').update(source).digest('hex').slice(0, 10);

// Higher = stronger. Used to say which source wins a disagreement and whether a claim rests only on weak support.
export const TRUST_RANK: Record<TrustClass, number> = {
  measured: 5,
  'vendor-official': 4,
  derived: 3,
  'user-supplied': 2,
  'community-mirror': 1,
  unknown: 0,
};
