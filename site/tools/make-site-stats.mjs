// Writes site/assets/site-stats.js: the headline numbers on the home page, computed from the generated data files, so they cannot drift.
// The home page loads this small file instead of the multi-megabyte parts data.   node site/tools/make-site-stats.mjs   (from the project root)
import * as fs from 'node:fs';
import * as vm from 'node:vm';

const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ['atlas-data', 'parts-data', 'devices-data']) vm.runInContext(fs.readFileSync(`site/assets/${f}.js`, 'utf8'), ctx);
const { ATLAS, PARTS, DEVICES } = ctx.window;

const quotes = (c) => (c ? (c.all ?? [c.q]).length : 0);
const quotesOf = (d) =>
  quotes(d.addressCite) + d.registers.reduce((n, r) => n + quotes(r.cite), 0) + d.facts.reduce((n, f) => n + quotes(f.cite), 0) + quotes(d.cycleTable?.cite);

const stats = {
  generated: new Date().toISOString().slice(0, 10),
  boards: ATLAS.meta.counts.boards,
  mcus: ATLAS.meta.counts.mcus,
  parts: PARTS.meta.counts.parts,
  manufacturers: PARTS.meta.vendors.length,
  vendorProfiles: PARTS.meta.vendorProfiles.vendors.length,
  models: DEVICES.devices.length,
  registersModeled: DEVICES.devices.reduce((n, d) => n + d.registers.length, 0),
  quotesChecked: DEVICES.devices.reduce((n, d) => n + quotesOf(d), 0),
};
fs.writeFileSync(
  'site/assets/site-stats.js',
  `/* Generated by site/tools/make-site-stats.mjs from the data files. Do not edit. */\nwindow.SITE_STATS=${JSON.stringify(stats)};\n`,
);
// The home page only needs the Atlas summary (counts and top vendors), not the 270 KB of board rows.
fs.writeFileSync(
  'site/assets/atlas-meta.js',
  `/* Generated by site/tools/make-site-stats.mjs: the summary of atlas-data.js without the rows. Do not edit. */\nwindow.ATLAS=${JSON.stringify({ meta: ATLAS.meta })};\n`,
);
console.log(JSON.stringify(stats));
