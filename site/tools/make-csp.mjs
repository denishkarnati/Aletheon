// Writes the Content-Security-Policy of every site page and the deployable site/_headers file.
//   node site/tools/make-csp.mjs          (from the project root; run it AFTER prettier and after any change to an inline <script>)
//   node site/tools/test-csp.mjs          fails when a hash is stale or a page has no policy
//
// How it works: scripts are only allowed from this site ('self') or by the SHA-256 of an exact inline <script>, so an injected script cannot
// run. Inline styles are allowed (the pages use style="..." attributes), which is a much smaller risk than inline scripts.
// - Every page gets the policy as a <meta> tag, which works on any host (GitHub Pages included).
// - site/_headers carries the same policy as a real header plus the headers a <meta> tag cannot set (frame-ancestors, HSTS...). Netlify and
//   Cloudflare Pages read it; GitHub Pages ignores it, so there the meta policy is what protects you.
// - lab.html is the only page allowed 'unsafe-eval' (the Device Lab runs the visitor's own code in a Worker) and the only page that may start a
//   blob: Worker; its connect-src is 'none', so even that code cannot reach the network.
import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';

const SITE = 'site';
// The policy tag as prettier lays it out (one attribute per line, indented like the charset tag). Matches single- or multi-line forms.
const META_RE = /^([ \t]*)<meta\s+http-equiv="Content-Security-Policy"[^>]*>[ \t]*(\r?\n)/im;
const CHARSET_RE = /^([ \t]*)(<meta charset="utf-8"\s*\/?>)[ \t]*(\r?\n)/im;

// Inline scripts that the browser would execute (not JSON data blocks), as the browser sees their text: line endings normalised to LF.
export function inlineScripts(html) {
  const out = [];
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1];
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
    if (type && !['text/javascript', 'application/javascript', 'module'].includes(type)) continue;
    out.push(m[2].replace(/\r\n?/g, '\n'));
  }
  return out;
}
export const hashOf = (text) => `'sha256-${crypto.createHash('sha256').update(text, 'utf8').digest('base64')}'`;

export function policyFor(page, html, { header = false } = {}) {
  const lab = page === 'lab.html';
  const scripts = ["'self'", ...(lab ? ["'unsafe-eval'"] : []), ...[...new Set(inlineScripts(html).map(hashOf))]];
  const d = [
    ['default-src', "'none'"],
    ['script-src', ...scripts],
    ['style-src', "'self'", "'unsafe-inline'"],
    ['img-src', "'self'", 'data:'],
    ['font-src', "'self'"],
    ['connect-src', lab ? "'none'" : "'self'"],
    ...(lab ? [['worker-src', 'blob:']] : []),
    ['base-uri', "'none'"],
    ['form-action', "'none'"],
    ['object-src', "'none'"],
    ...(header ? [['frame-ancestors', "'none'"]] : []), // ignored in a <meta> tag, so only sent as a header
  ];
  return d.map((x) => x.join(' ')).join('; ');
}

export const OTHER_HEADERS = [
  ['X-Content-Type-Options', 'nosniff'],
  ['X-Frame-Options', 'DENY'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  [
    'Permissions-Policy',
    'accelerometer=(), autoplay=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), midi=(), payment=(), publickey-credentials-get=(), usb=(), interest-cohort=()',
  ],
  ['Cross-Origin-Opener-Policy', 'same-origin'],
  ['Strict-Transport-Security', 'max-age=31536000; includeSubDomains'],
];

// Caching. Pages revalidate quickly; assets are cached for a day and served stale while they refresh. Not "immutable": the generated data
// files (atlas, parts, devices) keep their names when they are rebuilt. No Content-Encoding rule: Netlify and Cloudflare compress on their own.
export const PAGE_CACHE = 'public, max-age=300, must-revalidate';
export const ASSET_CACHE = 'public, max-age=86400, stale-while-revalidate=604800';

export function applyMeta(html, csp) {
  const tag = (ind, nl) => [`${ind}<meta`, `${ind}  http-equiv="Content-Security-Policy"`, `${ind}  content="${csp}"`, `${ind}/>`].join(nl) + nl;
  if (META_RE.test(html)) return html.replace(META_RE, (_, ind, nl) => tag(ind, nl));
  if (!CHARSET_RE.test(html)) throw new Error('page has no <meta charset="utf-8"> line to anchor the policy after');
  return html.replace(CHARSET_RE, (_, ind, charset, nl) => `${ind}${charset}${nl}${tag(ind, nl)}`);
}

if (process.argv[1] && path.basename(process.argv[1]) === 'make-csp.mjs') {
  const pages = fs
    .readdirSync(SITE)
    .filter((f) => f.endsWith('.html'))
    .sort();
  const lines = [
    '# Generated by site/tools/make-csp.mjs. Do not edit by hand; put extra rules in site/tools/headers-extra.txt and re-run the tool.',
    '# Netlify and Cloudflare Pages read this file. GitHub Pages ignores it (the <meta> policy in every page still applies there).',
    '# A page lists its OWN Content-Security-Policy, because policies that match more than one rule would all be enforced together.',
    '',
    '/*',
    ...OTHER_HEADERS.map(([k, v]) => `  ${k}: ${v}`),
    '',
  ];
  for (const f of pages) {
    const file = path.join(SITE, f);
    const html = fs.readFileSync(file, 'utf8');
    const next = applyMeta(html, policyFor(f, html));
    if (next !== html) fs.writeFileSync(file, next);
    const name = f.replace(/\.html$/, '');
    const paths = name === 'index' ? ['/', '/index.html'] : [`/${f}`, `/${name}`];
    for (const p of paths) lines.push(p, `  Content-Security-Policy: ${policyFor(f, html, { header: true })}`, `  Cache-Control: ${PAGE_CACHE}`, '');
    console.log(`${f}: ${inlineScripts(html).length} inline script(s) hashed${f === 'lab.html' ? ", 'unsafe-eval' + blob: worker, connect-src 'none'" : ''}`);
  }
  lines.push('/assets/*', `  Cache-Control: ${ASSET_CACHE}`, '');
  const extra = path.join(SITE, 'tools', 'headers-extra.txt');
  if (fs.existsSync(extra)) lines.push('# --- from site/tools/headers-extra.txt', fs.readFileSync(extra, 'utf8').trimEnd(), '');
  fs.writeFileSync(path.join(SITE, '_headers'), lines.join('\n'));
  console.log(`wrote ${SITE}/_headers (${pages.length} pages)`);
}
