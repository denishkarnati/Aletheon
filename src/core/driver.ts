import { SvdDevice, SvdPeripheral, SvdRegister } from './svd';

// Deterministic SVD -> C register header. Every address, offset, reset value and bit position comes
// straight from the parsed SVD, so the LLM only writes driver *logic* on top of verified definitions.

const C_KEYWORDS = new Set([
  'auto',
  'break',
  'case',
  'char',
  'const',
  'continue',
  'default',
  'do',
  'double',
  'else',
  'enum',
  'extern',
  'float',
  'for',
  'goto',
  'if',
  'inline',
  'int',
  'long',
  'register',
  'restrict',
  'return',
  'short',
  'signed',
  'sizeof',
  'static',
  'struct',
  'switch',
  'typedef',
  'union',
  'unsigned',
  'void',
  'volatile',
  'while',
  'bool',
  'class',
  'new',
  'delete',
  'template',
  'this',
  'namespace',
]);

const ident = (s: string): string => {
  let r = s.replace(/[^A-Za-z0-9_]/g, '_');
  if (/^\d/.test(r)) r = '_' + r;
  return r;
};
const member = (s: string): string => {
  const r = ident(s);
  return C_KEYWORDS.has(r.toLowerCase()) ? r + '_' : r;
};
const hex = (n: number | bigint, w = 8): string => '0x' + n.toString(16).toUpperCase().padStart(w, '0');
const cType = (bits: number): string => (bits <= 8 ? 'uint8_t' : bits <= 16 ? 'uint16_t' : bits <= 32 ? 'uint32_t' : 'uint64_t');
const lit = (n: number | bigint, wide: boolean): string => hex(n, wide ? 16 : 8) + (wide ? 'ULL' : 'u');
// Everything that comes from a vendor SVD is untrusted text: it must not be able to close a comment, open a string or start a new line of code.
const comment = (s?: string): string =>
  s
    ? s
        // eslint-disable-next-line no-control-regex
        .replace(/[\u0000-\u001f\u007f]+/g, ' ')
        .replace(/\*\//g, '* /')
        .replace(/\/\*/g, '/ *')
        .replace(/\\/g, '/')
        .slice(0, 160)
    : '';
// For text placed inside a "..." C string literal.
const cstr = (s: string): string =>
  s
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f]+/g, ' ')
    .replace(/[\\"]/g, '_')
    .slice(0, 80);

export interface GeneratedHeader {
  text: string;
  registers: number;
  fields: number;
  structMembers: number;
  skipped: string[]; // registers left out of the struct (overlap/misalignment); address macros still emitted
}

export function headerGuard(dev: SvdDevice, p: SvdPeripheral): string {
  return `ALETHEON_${ident(dev.name).toUpperCase()}_${ident(p.name).toUpperCase()}_REGS_H`;
}

export function generateRegsHeader(dev: SvdDevice, p: SvdPeripheral, evidenceId: string): GeneratedHeader {
  const P = ident(p.name).toUpperCase();
  const guard = headerGuard(dev, p);
  const L: string[] = [];
  let fields = 0;

  L.push(
    `/* ${P} register definitions for ${comment(dev.name)}`,
    ` * GENERATED by Aletheon from CMSIS-SVD. Do not edit; regenerate instead.`,
    ` * Source: ${comment(dev.source)}`,
    ` * Evidence: [${evidenceId}]  Base address: ${hex(p.base)}`,
    ` */`,
    `#ifndef ${guard}`,
    `#define ${guard}`,
    ``,
    `#include <stdint.h>`,
    `#include <stddef.h>`,
    ``,
    `#define ${P}_BASE ${hex(p.base)}u`,
    ``,
  );

  const used = new Set<string>();
  const define = (name: string, value: string, doc?: string): void => {
    if (used.has(name)) return; // identical macro names would redefine; first wins, deterministic order
    used.add(name);
    L.push(`#define ${name} ${value}${doc ? ` /* ${comment(doc)} */` : ''}`);
  };

  for (const r of p.registers) {
    const R = `${P}_${ident(r.name).toUpperCase()}`;
    const wide = r.size > 32;
    L.push(`/* ${comment(r.name)}: ${comment(r.description)} (${comment(r.access ?? 'n/a')}, ${r.size}-bit) */`);
    define(`${R}_OFFSET`, `${hex(r.offset, 3)}u`);
    define(`${R}_ADDR`, `(${P}_BASE + ${R}_OFFSET)`);
    define(`${R}_REG`, `(*(volatile ${cType(r.size)} *)${R}_ADDR)`);
    if (r.reset !== undefined) define(`${R}_RESET`, lit(r.reset, wide));
    for (const f of r.fields) {
      const F = `${R}_${ident(f.name).toUpperCase()}`;
      const width = f.msb - f.lsb + 1;
      const fwide = wide || f.msb > 31;
      const mask = ((1n << BigInt(width)) - 1n) << BigInt(f.lsb);
      define(`${F}_Pos`, `${f.lsb}u`, f.description);
      define(`${F}_Msk`, lit(mask, fwide));
      fields++;
      for (const e of f.enums ?? []) {
        const v = e.value.match(/^(0x[0-9a-f]+|#[01]+|\d+)$/i) ? (e.value.startsWith('#') ? parseInt(e.value.slice(1), 2) : Number(e.value)) : undefined;
        if (v !== undefined && e.name) define(`${F}_${ident(e.name).toUpperCase()}`, `${v}u`, e.description);
      }
    }
    L.push('');
  }

  // Struct view: registers in offset order, gaps as reserved bytes. Overlapping/misaligned registers
  // (aliases, unions) keep their address macros but are excluded so the layout stays provable.
  const skipped: string[] = [];
  const ordered = [...p.registers].sort((a, b) => a.offset - b.offset || a.name.localeCompare(b.name));
  const members: { r: SvdRegister; name: string; gap: number }[] = [];
  const names = new Set<string>();
  let cursor = 0;
  for (const r of ordered) {
    const bytes = r.size / 8;
    if (r.offset < cursor || r.offset % bytes !== 0 || !Number.isInteger(bytes)) {
      skipped.push(r.name);
      continue;
    }
    let name = member(r.name);
    if (names.has(name)) name = `${name}_${r.offset.toString(16)}`;
    names.add(name);
    members.push({ r, name, gap: r.offset - cursor });
    cursor = r.offset + bytes;
  }
  if (members.length) {
    L.push(`typedef struct {`);
    let rsv = 0;
    for (const m of members) {
      if (m.gap) L.push(`  uint8_t _reserved${rsv++}[${m.gap}];`);
      L.push(`  volatile ${cType(m.r.size)} ${m.name}; /* ${hex(m.r.offset, 3)} ${comment(m.r.access ?? '')} */`);
    }
    // Named P_REGS, not bare P: a bare "POWER" macro would rewrite the member `POWER` in another peripheral's struct (nRF52840 RADIO).
    L.push(`} ${P}_Type;`, ``, `#define ${P}_REGS ((${P}_Type *)${P}_BASE)`, ``);
    L.push(
      `/* Layout proof: struct offsets must equal the SVD offsets. */`,
      `#ifndef ALETHEON_NO_LAYOUT_CHECKS`,
      `#ifdef __cplusplus`,
      `#define ALETHEON_ASSERT(c, m) static_assert(c, m)`,
      `#else`,
      `#define ALETHEON_ASSERT(c, m) _Static_assert(c, m)`,
      `#endif`,
    );
    for (const m of members)
      L.push(`ALETHEON_ASSERT(offsetof(${P}_Type, ${m.name}) == ${hex(m.r.offset, 3)}u, "${cstr(P)}.${cstr(m.r.name)} offset differs from SVD");`);
    L.push(`#endif`, ``);
  }
  if (skipped.length) L.push(`/* Not in ${P}_Type (overlap/misaligned; use the _REG/_ADDR macros): ${skipped.map((n) => comment(n)).join(', ')} */`, ``);
  L.push(`#endif /* ${guard} */`, ``);

  return { text: L.join('\n'), registers: p.registers.length, fields, structMembers: members.length, skipped };
}
